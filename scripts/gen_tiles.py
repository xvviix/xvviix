            f'  <g clip-path="url(#{pfx}-clip)">\n'
            f'    <rect x="8" y="8" width="184" height="97" fill="url(#{pfx}-ph)"/>\n'
            f'    <rect x="8" y="8" width="184" height="97" fill="url(#{pfx}-grid)"/>\n'
            f'    <text x="100" y="64" text-anchor="middle" font-family="ui-monospace,'
