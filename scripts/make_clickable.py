#!/usr/bin/env python3
"""What-I-Build + Social: clickable via the PROVEN tile pattern.

GitHub strips inline <svg> from profile READMEs (the markup shows up as
escaped text). The only clickable pattern that definitely works is what the
"Projects, live" grid uses: <a href="..."><img src="*.svg"/></a>.

So each site chip and each social chip becomes its own small SVG (same
aurora-dark kit styling) and the README lays them out per category:

  title strip (img)
  [category pill (img)] [chip (a>img)] [chip (a>img)] ...   <- wraps naturally
  ...
  footer strip (a>img -> repos tab)

  social: [github (a>img)] [email (a>img)] [telegram (a>img)]

Re-running is idempotent: everything is rewritten and the README blocks
between the GITSKINS:WIB / GITSKINS:SOCIAL markers are regenerated.
"""
