def esc(s):
    return html.escape(s, quote=False)


def fetch_wib_rows():
    """Parse rows (category + [(repo, label)]) from gitskins/what-i-build.svg."""
    svg = open(os.path.join(ROOT, "gitskins", "what-i-build.svg"), encoding="utf-8").read()
    rows = []
    for m in re.finditer(r'<g class="wib-row"[^>]*>(.*?)</g>', svg, re.S):
        body = m.group(1)
        name_m = re.search(
            r'<text x="84" y="[\d.]+" font-family="[^"]*" font-size="12" '
            r'font-weight="800"[^>]*>([^<]+)</text>', body)
        chips = []
        for a in re.finditer(
                r'<a href="https://github\.com/' + USER + r'/([^"]+)">'
                r'<title>([^<]+)</title>', body):
            chips.append((a.group(1), html.unescape(a.group(2))))
        rows.append((html.unescape(name_m.group(1)), chips))
    if len(rows) != len(CATEGORIES):
        sys.exit(f"expected {len(CATEGORIES)} wib rows, parsed {len(rows)}")
    return rows


