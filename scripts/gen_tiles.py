def build_grid(tiles: list) -> str:
    lines = ['<div align="center">']
    for t in tiles:
        lines.append(
            f'<a href="{t["url"]}"><img src="{RAW}/gitskins/tiles/{t["name"]}.svg" '
            f'width="200" title="{e(t["disp"])}" alt="{e(t["disp"])}"/></a>'
        )
    lines.append("</div>")
    return "\n".join(lines)


def main():
    # ---- fetch live pages repos (with Link header pagination) ----
    url = f"/users/{USER}/repos?per_page=100&type=owner"
    repos = []
    while url:
        hdrs = {"User-Agent": "xvviix-profile-gen/1.0"}
        if TOKEN:
            hdrs["Authorization"] = "Bearer " + TOKEN
        req = urllib.request.Request("https://api.github.com" + url, headers=hdrs)
        with urllib.request.urlopen(req, timeout=30) as r:
            repos.extend(json.loads(r.read()))
            m = re.search(r'<([^>]+)>;\s*rel="next"', r.headers.get("Link", ""))
            url = m.group(1) if m else None

    pages = [r for r in repos if r.get("has_pages")]
    if not pages:
        raise SystemExit("no has_pages repos — refusing to wipe the section")

    by_name = {r["name"]: r for r in pages}
    order = [n for n in CURATED_ORDER if n in by_name]
    rest = sorted(
        (r for r in pages if r["name"] not in CURATED_ORDER),
        key=lambda r: (-r.get("stargazers_count") or 0, r["name"].lower()),
    )
    order += [r["name"] for r in rest]

    os.makedirs(TILES, exist_ok=True)
    tiles, written, placeholder_n = [], 0, 0
    for name in order:
        repo = by_name[name]
        disp = display_name(repo)
        b64 = None
        shot = os.path.join(SHOTS, name + ".jpg")
        if not os.path.exists(shot):
            shot = os.path.join(SHOTS, name + ".png")
        if os.path.exists(shot):
            b64 = shot_to_b64(shot)
        elif not INCLUDE_PLACEHOLDERS:
            continue
        else:
            placeholder_n += 1
        svg = render_tile(repo, b64)
        xml.dom.minidom.parseString(svg)          # validate before writing
        path = os.path.join(TILES, name + ".svg")
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != svg:
            with open(path, "w", encoding="utf-8") as f:
                f.write(svg)
            written += 1
        tiles.append({"name": name, "disp": disp, "url": site_url(repo)})

    # drop tiles for repos that lost Pages
    for f in os.listdir(TILES):
        if f.endswith(".svg") and f[:-4] not in by_name:
            os.remove(os.path.join(TILES, f))
            print("removed stale tile:", f)

    # ---- update README grid between markers ----
    readme = open(README, encoding="utf-8").read()
    grid = build_grid(tiles)
    new = re.sub(
        re.escape(MARK_BEGIN) + r".*?" + re.escape(MARK_END),
        MARK_BEGIN + "\n" + grid + "\n" + MARK_END,
        readme, flags=re.S,
    )
    if new != readme:
        with open(README, "w", encoding="utf-8") as f:
            f.write(new)
        print("README grid updated")
    else:
        print("README grid unchanged")

    print(f"{len(tiles)} live sites ({len(tiles) - placeholder_n} with shot, "
          f"{placeholder_n} placeholder) — {written} tile file(s) written")


if __name__ == "__main__":
    main()
