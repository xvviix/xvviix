def install_readme(section, block, img_fallback):
    """Replace the GITSKINS:<section> marker block (any variant) or, on first
    run, the legacy <img> block."""
    cur = open(README, encoding="utf-8").read()
    pat = re.compile(
        r"<!-- GITSKINS:" + section + r":BEGIN[^>]*-->.*?"
        r"<!-- GITSKINS:" + section + r":END -->", re.S)
    if pat.search(cur):
        cur = pat.sub(lambda _m: block, cur, count=1)
    else:
        if not img_fallback.search(cur):
            sys.exit(f"README: neither marker block nor <img> fallback found for {section!r}")
        cur = img_fallback.sub(lambda _m: block, cur, count=1)
    open(README, "w", encoding="utf-8").write(cur)
    print(f"README: {section} block installed")


def main():
    os.makedirs(WIB_DIR, exist_ok=True)
    os.makedirs(SOC_DIR, exist_ok=True)

    rows = fetch_wib_rows()

    # ---- assets ----
    open(os.path.join(WIB_DIR, "title.svg"), "w", encoding="utf-8").write(title_svg())
    open(os.path.join(WIB_DIR, "footer.svg"), "w", encoding="utf-8").write(footer_svg())
    for i, (emoji, _name) in enumerate(CATEGORIES, 1):
        open(os.path.join(WIB_DIR, f"cat-{i}.svg"), "w", encoding="utf-8").write(
            cat_svg(emoji, rows[i - 1][0]))
    n = 0
    for _cat, chips in rows:
        for repo, label in chips:
            open(os.path.join(WIB_DIR, f"chip-{repo}.svg"), "w", encoding="utf-8").write(
                chip_svg(repo, label))
            n += 1
    for kind in ("github", "email", "telegram"):
        open(os.path.join(SOC_DIR, f"{kind}.svg"), "w", encoding="utf-8").write(social_chip(kind))
    print(f"wrote title, footer, {len(CATEGORIES)} category pills, {n} chips, 3 social chips")

    # ---- README: what i build ----
    lines = [WIB_MARK, '<div align="center">',
             f'<img src="{RAW}/wib/title.svg" alt="What I build — project catalog by industry" width="860"/>',
             "<br/>"]
    for i, (_emoji, _name) in enumerate(CATEGORIES, 1):
        _cat, chips = rows[i - 1]
        lines.append('<div>')
        lines.append(f'<img src="{RAW}/wib/cat-{i}.svg" height="32" alt="{esc(_name)}"/>')
        for repo, label in chips:
            w = min(178, max(92, 74 + int(len((label if len(label) <= 17 else label[:16] + "…")) * 6.6)))
            lines.append(
                f'<a href="https://github.com/{USER}/{repo}">'
                f'<img src="{RAW}/wib/chip-{repo}.svg" width="{w}" height="44" '
                f'title="{esc(label)} — repo" alt="{esc(label)}"/></a>')
        lines.append("</div>")
    lines += ["<br/>",
              f'<a href="https://github.com/{USER}?tab=repositories">'
              f'<img src="{RAW}/wib/footer.svg" alt="view all repositories" width="860"/></a>',
              "</div>", WIB_END]
    wib_block = "\n".join(lines)
    wib_img = re.compile(
        r'<p align="center">\s*'
        r'(?:<a href="https://github\.com/xvviix\?tab=repositories">\s*)?'
        r'<img src="https://raw\.githubusercontent\.com/xvviix/xvviix/main/gitskins/what-i-build\.svg"[^>]*/>\s*'
        r'(?:</a>\s*)?</p>')
    install_readme("WIB", wib_block, wib_img)

    # ---- README: social ----
    soc_lines = [SOC_MARK, '<div align="center">',
                 f'<a href="https://github.com/{USER}">'
                 f'<img src="{RAW}/social-chips/github.svg" width="178" height="46" alt="GitHub"/></a>',
                 '<a href="mailto:matinhabibi688@gmail.com">'
                 f'<img src="{RAW}/social-chips/email.svg" width="252" height="46" alt="Email"/></a>',
                 f'<a href="https://t.me/{USER}">'
                 f'<img src="{RAW}/social-chips/telegram.svg" width="170" height="46" alt="Telegram"/></a>',
                 "</div>", SOC_END]
    soc_block = "\n".join(soc_lines)
    soc_img = re.compile(
        r'<p align="center">\s*'
        r'<img src="https://raw\.githubusercontent\.com/xvviix/xvviix/main/gitskins/social\.svg"[^>]*/>\s*'
        r'</p>')
    install_readme("SOCIAL", soc_block, soc_img)
    print("done.")


if __name__ == "__main__":
    main()
